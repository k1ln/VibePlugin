#!/usr/bin/env node
// embed-preset-ui.mjs
// =====================================================================
//  Bakes ui/preset-browser.js (the in-plugin sound browser) and ui/sound-bar.js into
//  src/PresetBrowserUi.h as a <script> the bridge injects into every GUI.
//  It has to live in the binary: an exported plugin strips Resources/ui.
//
//      node scripts/embed-preset-ui.mjs           regenerate the header
//      node scripts/embed-preset-ui.mjs --check   exit 1 if the header is stale
//
//  The JS is split into raw-string pieces of <= ~12 KB: MSVC rejects a single
//  string literal over 16 380 bytes, and adjacent literals concatenate.
// =====================================================================
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, "..", "ui", "preset-browser.js");
const BAR = path.join(HERE, "..", "ui", "sound-bar.js");   // the floating prev / name / Save bar, injected right after the drawer
const OUT = path.join(HERE, "..", "src", "PresetBrowserUi.h");
const DELIM = "PBUI";

const js = readFileSync(SRC, "utf8"), bar = readFileSync(BAR, "utf8");
for (const [n, t] of [["preset-browser.js", js], ["sound-bar.js", bar]]) {
  if (t.includes(`)${DELIM}"`)) throw new Error(n + " contains the raw-string terminator");
  if (/<\/script/i.test(t)) throw new Error(n + " must not contain </script>");
}

const body = `<script>\n${js}</script>\n<script>\n${bar}</script>`;
const pieces = [];
let cur = "";
for (const line of body.split("\n")) {
  const add = line + "\n";
  if (Buffer.byteLength(cur + add) > 12000 && cur) { pieces.push(cur); cur = ""; }
  cur += add;
}
pieces.push(cur.replace(/\n$/, ""));

const header = `// PresetBrowserUi.h
// =====================================================================
//  GENERATED by scripts/embed-preset-ui.mjs from ui/preset-browser.js + ui/sound-bar.js — do not edit
//  by hand. The in-plugin sound browser, injected after the bridge shim into every
//  generated GUI by vstai::shim::withBridge (BridgeShim.h).
// =====================================================================

#pragma once

namespace vstai::shim
{
    inline const char* kPresetBrowserUi =
${pieces.map((p) => `R"${DELIM}(${p})${DELIM}"`).join("\n")};
}
`;

if (process.argv.includes("--check")) {
  let have = "";
  try { have = readFileSync(OUT, "utf8"); } catch {}
  if (have !== header) { console.error("src/PresetBrowserUi.h is stale: run node scripts/embed-preset-ui.mjs"); process.exit(1); }
  console.log("PresetBrowserUi.h is up to date");
} else {
  writeFileSync(OUT, header);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${pieces.length} pieces, ${Buffer.byteLength(js)} bytes of JS)`);
}
