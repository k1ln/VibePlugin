export function process(n: i32): void {
  const sr: f32 = sampleRate;
  let pkIn: f32 = 0.0; let pkOut: f32 = 0.0;
  
  const sp: f32 = params[P_SPEED];
  const fA: f32 = tcK(0.0004); const fR: f32 = tcK(expMap(sp, 0.04, 0.008)); const sA: f32 = tcK(expMap(sp, 0.06, 0.012)); const sR: f32 = tcK(expMap(sp, 0.35, 0.12));
  const aDb: f32 = params[P_ATTACK]; const sDb: f32 = params[P_SUSTAIN]; const smK: f32 = tcK(0.001); const outG: f32 = dbLin(params[P_OUTPUT]);
  for (let f = 0; f < n; f++) {
    const xl: f32 = inBuf[f]; const xr: f32 = inBuf[MAX_FRAMES + f];
    let yl: f32 = xl; let yr: f32 = xr;
    
    
  const lv: f32 = maxf(absf(xl), absf(xr));
  tfast += (lv - tfast) * (lv > tfast ? fA : fR);
  tslow += (lv - tslow) * (lv > tslow ? sA : sR);
  const dd: f32 = linDb(tfast) - linDb(tslow);
  const trn: f32 = clampf(dd / 6.0, 0.0, 1.0); const sus: f32 = clampf(-dd / 6.0, 0.0, 1.0);
  const gate: f32 = tslow > 0.0005 ? 1.0 : 0.0;
  tg += ((trn * aDb + sus * sDb) * gate - tg) * smK;
  const g: f32 = dbLin(tg) * outG;
  yl = softLim(xl * g); yr = softLim(xr * g);
    if (!(yl == yl)) yl = 0.0; if (!(yr == yr)) yr = 0.0;
    outBuf[f] = yl; outBuf[MAX_FRAMES + f] = yr;
    pkIn = maxf(pkIn, maxf(absf(xl), absf(xr))); pkOut = maxf(pkOut, maxf(absf(yl), absf(yr)));
    
  }
  display[0] = maxf(display[0] * 0.8, clampf(pkOut, 0.0, 1.0));
  display[1] = maxf(display[1] * 0.8, clampf(pkIn, 0.0, 1.0));
  
}
