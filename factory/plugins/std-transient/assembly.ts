//  A transient shaper that changes the punch of a sound without any threshold to set. Two envelope followers, one fast and one slow, track the signal, and the difference between them separates the attack of each note from its sustained tail: when the fast follower is above the slow one a transient is happening, and when it falls below, the note is decaying. Attack boosts or cuts the transients by up to 12 dB and Sustain boosts or cuts the tails, so you can add snap to a dull snare, tighten a boomy kick, or dry out a roomy drum loop. Speed sets how fine the detection is.
