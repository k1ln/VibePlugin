export function init(sr: f32, maxFrames: i32, numChannels: i32): void {
  sampleRate = sr > 0.0 ? sr : 48000.0;
  hostPlaying = false; hostBpm = 120.0; beatPos = 0.0; seed = 12345;
  setDefaults();
  for (let i = 0; i < 16; i++) display[i] = 0.0;
  for (let i = 0; i < 2 * 2048; i++) lbuf[i] = 0.0; for (let i = 0; i < 2048; i++) gh[i] = 1.0; lw = 0; minV = 1.0; minPos = 0; gsm = 1.0;
}

export function process(n: i32): void {
  const sr: f32 = sampleRate;
  let pkIn: f32 = 0.0; let pkOut: f32 = 0.0;
  
  const LA: i32 = i32(clampf((0.5 + params[P_LOOKAHEAD] * 4.5) * 0.001 * sr, 8.0, 1900.0));
  const ceilL: f32 = dbLin(params[P_CEILING]); const inG: f32 = dbLin(params[P_GAIN]); const sc: f32 = params[P_SOFTCLIP];
  const relK: f32 = tcK(expMap(params[P_RELEASE], 10.0, 1000.0) * 0.001); const atkK: f32 = tcK(f32(LA) / sr * 0.25);
  let gMin: f32 = 1.0;
  for (let f = 0; f < n; f++) {
    const xl: f32 = inBuf[f]; const xr: f32 = inBuf[MAX_FRAMES + f];
    let yl: f32 = xl; let yr: f32 = xr;
    
    
  let vl: f32 = xl * inG; let vr: f32 = xr * inG;
  if (sc > 0.0) { vl = vl * (1.0 - sc) + tanhf(vl) * sc; vr = vr * (1.0 - sc) + tanhf(vr) * sc; }
  lbuf[lw] = vl; lbuf[2048 + lw] = vr;
  const pk: f32 = maxf(absf(vl), absf(vr)); const gReq: f32 = pk > ceilL ? ceilL / pk : 1.0;
  gh[lw] = gReq;
  const old: i32 = (lw - LA - 1) & 2047;
  if (gReq <= minV) { minV = gReq; minPos = lw; }
  else if (minPos == old) { minV = 1.0; for (let k: i32 = 0; k <= LA; k++) { const ix: i32 = (lw - k) & 2047; const gv: f32 = gh[ix]; if (gv < minV) { minV = gv; minPos = ix; } } }
  gsm += (minV - gsm) * (minV < gsm ? atkK : relK);
  const rd: i32 = (lw - LA) & 2047;
  yl = clampf(lbuf[rd] * gsm, -ceilL, ceilL); yr = clampf(lbuf[2048 + rd] * gsm, -ceilL, ceilL);
  lw = (lw + 1) & 2047;
  gMin = minf(gMin, gsm);
    if (!(yl == yl)) yl = 0.0; if (!(yr == yr)) yr = 0.0;
    outBuf[f] = yl; outBuf[MAX_FRAMES + f] = yr;
    pkIn = maxf(pkIn, maxf(absf(xl), absf(xr))); pkOut = maxf(pkOut, maxf(absf(yl), absf(yr)));
    
  }
  display[0] = maxf(display[0] * 0.8, clampf(pkOut, 0.0, 1.0));
  display[1] = maxf(display[1] * 0.8, clampf(pkIn, 0.0, 1.0));
  display[2] = clampf(-linDb(gMin) / 18.0, 0.0, 1.0);
}
