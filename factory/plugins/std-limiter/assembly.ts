// =====================================================================
//  STDLIMITER — Look-ahead brickwall limiter
//  A look-ahead brickwall limiter for the end of a chain. The audio is delayed by the Lookahead time while a sliding-window minimum finds the gain reduction each upcoming peak needs, and the gain is eased down before the peak arrives (so there is no overshoot or crackle) and released smoothly afterwards at the Release rate. Gain drives the signal into the limiter, Ceiling is the level nothing will ever exceed, and Soft Clip rounds the peaks with a tanh stage before limiting for a louder, warmer result with less gain reduction. Left and right are linked so the stereo image does not shift.
